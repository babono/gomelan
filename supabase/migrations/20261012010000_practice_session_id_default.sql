-- practice_session.id was NOT NULL with no default, and the app never sends
-- one — so every session insert since v1 failed with 23502 and the table
-- stayed empty. Give the column a generated default, whichever type it was
-- created with. Safe to re-run: it does nothing once a default exists.

do $$
declare
    col record;
begin
    select data_type, column_default, is_identity
      into col
      from information_schema.columns
     where table_schema = 'public'
       and table_name = 'practice_session'
       and column_name = 'id';

    if col.column_default is not null or col.is_identity = 'YES' then
        raise notice 'practice_session.id already has a default; nothing to do';
    elsif col.data_type = 'uuid' then
        alter table public.practice_session
            alter column id set default gen_random_uuid();
    elsif col.data_type in ('bigint', 'integer', 'smallint') then
        alter table public.practice_session
            alter column id add generated by default as identity;
    else
        raise exception 'practice_session.id is %, give it a default by hand', col.data_type;
    end if;
end
$$;
